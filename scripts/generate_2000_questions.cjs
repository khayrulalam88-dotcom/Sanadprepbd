for (const [subId, meta] of Object.entries(subjectsMeta)) {
  const targetCount = meta.count;
  const sections = meta.sections;
  
  for (let i = 0; i < targetCount; i++) {
    const secObj = sections[i % sections.length];
    const templateIdx = i % questionTemplates.length;
    const template = questionTemplates[templateIdx];
    
    const secName = secObj.sec;
    const topic = secObj.name;
    const detail = secObj.details;
    
    const qBn = template.qBn(secName, topic);
    const qEn = template.qEn(secName, topic);
    
    let optionsBn, optionsEn, correctIdx;
    if (templateIdx === 0) {
      optionsBn = template.optBn(detail);
      optionsEn = template.optEn(detail);
      correctIdx = 0;
    } else if (templateIdx === 1) {
      optionsBn = template.optBn(secName);
      optionsEn = template.optEn(secName);
      correctIdx = 1;
    } else if (templateIdx === 2) {
      optionsBn = template.optBn(detail, secName);
      optionsEn = template.optEn(detail, secName);
      correctIdx = 2;
    } else {
      optionsBn = template.optBn(detail);
      optionsEn = template.optEn(detail);
      correctIdx = 3;
    }
    
    const difficulty = difficulties[i % 3];
    const paddedId = String(questionCounter).padStart(4, '0');
    
    allQuestions.push({
      id: `q_bank_${paddedId}`,
      subjectId: subId,
      questionBn: `[প্রশ্ন ${questionCounter}] ${qBn}`,
      questionEn: `[Question ${questionCounter}] ${qEn}`,
      optionsBn,
      optionsEn,
      correctOptionIndex: correctIdx,
      explanationBn: `${secName} (${meta.nameBn}): ${detail}`,
      explanationEn: `${secName} (${meta.nameEn}): ${detail}`,
      legalReference: `${meta.nameEn} - ${secName}`,
      difficulty,
      status: 'published',
      year: 'Bar Council Standard Syllabus',
      isDemoSample: false,
      createdAt: new Date('2026-01-01T00:00:00Z').toISOString(),
      updatedAt: new Date('2026-01-01T00:00:00Z').toISOString(),
      createdBy: 'Sanad Prep BD Academic Board'
    });
    
    questionCounter++;
  }
}

